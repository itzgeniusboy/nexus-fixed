async function generate(ctx: PluginContext): Promise<number | void> {
  const query = ctx.args.join(" ")
  if (!query) {
    ctx.err("Usage: nexus code generate \"<description>\" --out ./dir")
    return 1
  }
  const outFlag = typeof ctx.flags.out === "string" ? ctx.flags.out : undefined
  const name = slug(query)
  const outDir = path.resolve(ctx.cwd, outFlag ?? `./${name}`)

  const template = TEMPLATES.find((t) => t.match.test(query)) ?? TEMPLATES[TEMPLATES.length - 1]
  const template_ = template as Template

  ctx.out(`${Icon.brain} Template: ${Style.TEXT_HIGHLIGHT}${template_.id}${Style.TEXT_NORMAL} (${template_.description})`)
  ctx.out(`${Icon.rocket} Generating at ${outDir}`)

  const fs = await import("fs/promises")
  await fs.mkdir(outDir, { recursive: true }).catch(() => {})

  for (const [relPath, content] of Object.entries(template_.files)) {
    const target = path.join(outDir, relPath)
    await fs.mkdir(path.dirname(target), { recursive: true }).catch(() => {})
    await fs.writeFile(target, content.replaceAll("{{name}}", name))
    ctx.out(`  ${Icon.success} ${relPath}`)
  }

  ctx.out(`${EOL}${Icon.success} Project created: ${Style.TEXT_SUCCESS_BOLD}${outDir}${Style.TEXT_NORMAL}`)
}

function slug(input: string): string {
  return input
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .split(/\s+/)
    .slice(0, 4)
    .join("-") || "nexus-project"
}

async function dockerize(ctx: PluginContext): Promise<number | void> {
  const target = path.resolve(ctx.cwd, ctx.args[0] ?? ".")
  const fs = await import("fs/promises")
  let entries: string[] = []
  try {
    entries = await fs.readdir(target)
  } catch {
    ctx.err(`Directory not found: ${target}`)
    return 1
  }

  const dockerfile = entries.includes("package.json")
    ? `FROM node:20-alpine
WORKDIR /app
COPY package*.json ./
RUN npm ci --omit=dev
COPY . .
EXPOSE 3000
CMD ["npm", "start"]
`
    : entries.includes("composer.json")
      ? `FROM php:8.3-apache
COPY . /var/www/html/
EXPOSE 80
`
      : entries.includes("requirements.txt")
        ? `FROM python:3.12-slim
WORKDIR /app
COPY requirements.txt .
RUN pip install -r requirements.txt
COPY . .
CMD ["python", "main.py"]
`
        : undefined

  if (!dockerfile) {
    ctx.err("Could not detect project type (looked for package.json, composer.json, requirements.txt)")
    return 1
  }

  await fs.writeFile(path.join(target, "Dockerfile"), dockerfile)
  await fs.writeFile(
    path.join(target, ".dockerignore"),
    "node_modules\n.git\ndist\nbuild\n.env\n",
  )
  ctx.out(`${Icon.success} Dockerfile + .dockerignore written to ${target}`)
}

async function serve(ctx: PluginContext): Promise<number | void> {
  const port = String(ctx.flags.port ?? 3000)
  const target = path.resolve(ctx.cwd, ctx.args[0] ?? ".")
  const proc = Bun.spawn(["python3", "-m", "http.server", port], {
    cwd: target,
    stdout: "inherit",
    stderr: "inherit",
  })
  ctx.out(`${Icon.info} Serving ${target} at ${Style.TEXT_HIGHLIGHT_BOLD}http://localhost:${port}${Style.TEXT_NORMAL} (Ctrl+C to stop)`)
  await proc.exited
}

async function convert(ctx: PluginContext): Promise<number | void> {
  const mod = await import("./translator")
  const translator = mod.default as NexusPlugin
  const translate = translator.commands.find((c) => c.name === "translate")
  if (!translate) {
    ctx.err("Translator plugin unavailable")
    return 1
  }
  ctx.out(`${Icon.info} Delegating to translator plugin...`)
  return translate.run(ctx)
}

async function composeAndCI(ctx: PluginContext): Promise<number | void> {
  const target = path.resolve(ctx.cwd, ctx.args[0] ?? ".")
  const fs = await import("fs/promises")
  if (!(await Bun.file(path.join(target, "Dockerfile")).exists())) {
    await dockerize({ ...ctx, args: [target] })
  }
  await fs.writeFile(
    path.join(target, "docker-compose.yml"),
    `services:\n  app:\n    build: .\n    ports:\n      - "3000:3000"\n    env_file:\n      - .env\n    restart: unless-stopped\n`,
  )
  await fs.mkdir(path.join(target, ".github", "workflows"), { recursive: true })
  await fs.writeFile(
    path.join(target, ".github", "workflows", "ci.yml"),
    `name: CI\non:\n  push:\n    branches: [main]\n  pull_request:\n\njobs:\n  build:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n      - uses: actions/setup-node@v4\n        with:\n          node-version: 20\n      - run: npm ci || npm install\n      - run: npm test --if-present\n      - run: npm run build --if-present\n`,
  )
  ctx.out(`${Icon.success} docker-compose.yml + GitHub Actions CI generated in ${target}`)
}

